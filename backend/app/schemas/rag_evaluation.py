from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional


class RAGEvaluationRequest(BaseModel):
    """Request model for RAG evaluation"""
    query: str = Field(..., description="The original user query", min_length=1)
    context: str = Field(..., description="The retrieved context chunks", min_length=1)
    llm_output: str = Field(..., description="The answer generated by the LLM", min_length=1)
    
    class Config:
        json_schema_extra = {
            "example": {
                "query": "What did the fox do?",
                "context": "A quick brown fox named Vixey jumps over the lazy dog. The dog, named Frodo, did not even open its eyes. The fox then ran into the forest.",
                "llm_output": "The quick brown fox, Vixey, jumped over Sparky, the lazy dog. The fox's jump was very high. After that, it ran away."
            }
        }


class SentenceEvaluation(BaseModel):
    """Model for individual sentence evaluation"""
    sentence_number: int
    sentence_text: str
    classification: str  # faithful, inferred, extrapolated, hallucinated
    justification: str
    supporting_chunk: str


class AggregateMetrics(BaseModel):
    """Model for aggregate evaluation metrics"""
    faithfulness_rate: float
    hallucination_rate: float
    inferred_rate: float
    extrapolated_rate: float
    precision: float
    recall: float
    f1_score: float
    total_sentences: int
    faithful_count: int
    hallucination_count: int
    inferred_count: int
    extrapolated_count: int


class RAGEvaluationResponse(BaseModel):
    """Response model for RAG evaluation"""
    status: str
    aggregate_metrics: Optional[AggregateMetrics] = None
    sentence_evaluations: Optional[List[SentenceEvaluation]] = None
    error: Optional[str] = None
    raw_response: Optional[str] = None